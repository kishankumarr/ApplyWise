const DAY_MS = 86_400_000;
const FIRST_JOB_ID = 7101;

/** "Reelcraft Studio" -> "reelcraft-studio" (used for .example / .test hosts). */
export function demoCompanySlug(company: string): string {
  return company
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/&/g, " and ")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function scenarioOf(spec: AutomationJobSpec): DemoScenario {
  return spec.scenario ?? (MANUAL_SOURCES.has(spec.source) ? "manual_only" : "auto_success");
}

function channelOf(spec: AutomationJobSpec): DemoChannel {
  return spec.channel ?? "api";
}

const skillName = (s: string) => s.replace(/\s*\((?:must|mandatory|required)\)\s*$/i, "").trim();
const isMandatory = (s: string) => /\((?:must|mandatory|required)\)\s*$/i.test(s);

function applyUrlOf(spec: AutomationJobSpec, id: number, appUrl: string): string {
  if (channelOf(spec) === "browser") return `${appUrl.replace(/\/+$/, "")}/demo/ats/greenhouse/${spec.key}`;
  return `https://careers.${demoCompanySlug(spec.company)}.example/jobs/${id}`;
}

function hrEmailOf(spec: AutomationJobSpec): string | undefined {
  return spec.hrEmail ? `hiring@${demoCompanySlug(spec.company)}.test` : undefined;
}

function description(spec: AutomationJobSpec, applyUrl: string, hrEmail: string | undefined): string {
  const [min, max] = spec.yoe;
  const lines: string[] = [
    DEMO_NOTICE,
    "",
    `${spec.title} at ${spec.company}`,
    "",
    "About us",
    spec.about,
    "",
    "What you'll do",
    ...spec.responsibilities.map((r) => `- ${r}`),
    "",
    "Requirements",
    `- ${min}-${max} years of professional experience`,
    ...spec.required.map((s) => (isMandatory(s) ? `- Must have strong hands-on experience with ${skillName(s)}` : `- Experience with ${skillName(s)}`)),
    ...(spec.extras ?? []).map((e) => `- ${e}`),
  ];
  if (spec.preferred.length > 0) lines.push("", "Nice to have", ...spec.preferred.map((s) => `- ${s}`));
  lines.push("", `Location: ${spec.locations.join(", ")} (${spec.workMode})`);
  if (spec.salaryLpa) lines.push(`Compensation: ${spec.salaryLpa[0]}-${spec.salaryLpa[1]} LPA`);
  if (spec.screening?.length) lines.push("", "Screening questions", ...spec.screening.map((q) => `- ${q}`));
  lines.push("", "How to apply");
  lines.push(hrEmail ? `Email your resume to ${hrEmail} with the subject "${spec.title} - <your name>".` : `Apply on the official page: ${applyUrl}`);
  return lines.join("\n");
}

function toRaw(spec: AutomationJobSpec, index: number, sourceId: DemoSourceId, appUrl: string, now: Date): RawImportedJob {
  const source = DEMO_SOURCES[sourceId];
  const id = FIRST_JOB_ID + index;
  const slug = demoCompanySlug(spec.company);
  const applyUrl = applyUrlOf(spec, id, appUrl);
  const hrEmail = hrEmailOf(spec);
  // Hours offset keeps postings from the same day apart; still a pure function of `now`.
  const posted = new Date(now.getTime() - spec.postedDaysAgo * DAY_MS - (index % 9) * 3_600_000);
  const expires = new Date(posted.getTime() + 60 * DAY_MS);
  const scenario = scenarioOf(spec);
  const channel = channelOf(spec);
  return {
    provider: source.platform,
    importMethod: "SEEDED_DEMO",
    externalId: `demo:${sourceId}:${id}`,
    sourceUrl: sourceId === "careers" && channel === "api" ? applyUrl : source.listingUrl({ key: spec.key, id, slug }),
    attribution: source.label,
    raw: { kind: "demo_provider", demo: true, demoScenario: scenario, demoChannel: channel, demoSource: sourceId, key: spec.key },
    text: description(spec, applyUrl, hrEmail),
    descriptionLevel: "FULL",
    hints: {
      platform: source.platform,
      title: spec.title,
      company: spec.company,
      companyWebsite: `https://${slug}.example`,
      location: spec.locations,
      workMode: spec.workMode,
      employmentType: "full_time",
      requiredSkillNames: spec.required.map((s) => (isMandatory(s) ? `${skillName(s)} (must)` : s)),
      preferredSkillNames: spec.preferred,
      experienceMinYears: spec.yoe[0],
      experienceMaxYears: spec.yoe[1],
      salaryMin: spec.salaryLpa ? spec.salaryLpa[0] * 100_000 : undefined,
      salaryMax: spec.salaryLpa ? spec.salaryLpa[1] * 100_000 : undefined,
      currency: spec.salaryLpa ? "INR" : undefined,
      postedAt: posted.toISOString(),
      expiresAt: expires.toISOString(),
      applyUrl,
      hrEmail,
      applyMethod: hrEmail ? "EMAIL" : undefined,
      applicationInstructions: hrEmail ? `Email your resume to ${hrEmail} with the subject "${spec.title} - <your name>".` : undefined,
      responsibilities: spec.responsibilities,
      isDemo: true,
    },
  };
}

/** Number of distinct jobs in the catalogue (the most `count` can return). */
export const DEMO_AUTOMATION_JOB_COUNT = CATALOGUE.length;

/**
 * 100+ deterministic demo jobs across simulated providers, followed by cross-provider duplicates (the same
 * title + company + primary city from another simulated source, so the import merges them into one job).
 */
export function generateDemoAutomationJobs(opts: DemoJobsOptions): RawImportedJob[] {
  const now = opts.now ?? new Date();
  const count = Math.max(0, Math.min(opts.count ?? 110, CATALOGUE.length));
  const specs = CATALOGUE.slice(0, count);
  const jobs = specs.map((spec, i) => toRaw(spec, i, spec.source, opts.appUrl, now));
  specs.forEach((spec, i) => {
    for (const other of spec.alsoOn ?? []) if (other !== spec.source) jobs.push(toRaw(spec, i, other, opts.appUrl, now));
  });
  return jobs;
}

/** The job's tier in the catalogue (tests and the score-distribution script compare it with the real score). */
export function demoAutomationJobTier(key: string): DemoTier | null {
  return CATALOGUE.find((s) => s.key === key)?.tier ?? null;
}

// ---------------------------------------------------------------- demo ATS page

export const DEMO_NOTICE_PERIOD_QUESTION = "What is your notice period?";
export const DEMO_WORK_AUTH_QUESTION = "Are you authorised to work in India?";
export const DEMO_SINGAPORE_PERMIT_QUESTION = "Do you hold a valid work permit for Singapore?";

export interface DemoAtsJob {
  title: string;
  company: string;
  locations: string[];
  /** Extra questions on the page (the standard fields - name, email, notice period, resume - are always there). */
  screening: string[];
  variant: "standard" | "captcha" | "login";
  applyUrl: string;
}

/** A demo job for the local demo ATS page (/demo/ats/<platform>/<slug>), or null. */
export function demoAutomationJobBySlug(slug: string, opts: { appUrl: string }): DemoAtsJob | null {
  const index = CATALOGUE.findIndex((s) => s.key === slug);
  const spec = CATALOGUE[index];
  if (!spec) return null;
  const scenario = scenarioOf(spec);
  const screening = [DEMO_WORK_AUTH_QUESTION, ...(scenario === "unknown_question" ? [DEMO_SINGAPORE_PERMIT_QUESTION] : []), ...(spec.screening ?? [])];
  return {
    title: spec.title,
    company: spec.company,
    locations: [...spec.locations],
    screening: [...new Set(screening.filter((q) => q !== DEMO_NOTICE_PERIOD_QUESTION))],
    variant: scenario === "captcha" ? "captcha" : scenario === "login_required" || scenario === "mfa" ? "login" : "standard",
    applyUrl: applyUrlOf(spec, FIRST_JOB_ID + index, opts.appUrl),
  };
}
