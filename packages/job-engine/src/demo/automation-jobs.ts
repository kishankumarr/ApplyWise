/**
 * DEMO CONTENT for the automation demo provider. Every company, job, URL and email address below is fictional:
 * career sites use the reserved .example TLD, HR addresses the reserved .test TLD, and the two browser-executor
 * jobs point at the local demo ATS pages served by the web app under /demo/ats/*.
 *
 * The catalogue is tuned against the seeded demo candidate (React/TypeScript frontend engineer, 5 years,
 * Bengaluru / Remote - India) so the REAL matching engine spreads it over three bands - verify with
 * `cd packages/database && npx tsx scripts/demo-score-distribution.ts`:
 *  - high:   score >= 90 (auto-apply candidates, each carrying one scripted outcome)
 *  - medium: 70-89 (review / recommend)
 *  - low:    below 70 (Java backend, data, DevOps, QA, native mobile, sales, ...)
 * Nothing here is random: the same `now` always yields the same jobs.
 */

export const DEMO_SCENARIOS = [
  /** Submits successfully on the first attempt. */
  "auto_success",
  /** First attempt fails with a retryable error, the retry succeeds. */
  "transient_failure",
  /** Fails permanently (e.g. the posting closed). */
  "permanent_failure",
  /** The application page shows a CAPTCHA -> MANUAL_ACTION_REQUIRED (never bypassed). */
  "captcha",
  "login_required",
  "mfa",
  /** The provider asks a required question the candidate never answered -> NEEDS_INFORMATION. */
  "unknown_question",
  /** Submits, then the status sync reports these outcomes (and a simulated recruiter email). */
  "assessment",
  "interview",
  "rejection",
  "offer",
  /** Simulates a platform without automatic application support (LinkedIn/Naukri-like) -> manual handoff. */
  "manual_only",
] as const;
export type DemoScenario = (typeof DEMO_SCENARIOS)[number];

export function isDemoScenario(value: unknown): value is DemoScenario {
  return typeof value === "string" && (DEMO_SCENARIOS as readonly string[]).includes(value);
}

/** "api": the demo provider's simulated API. "browser": the demo ATS page, filled by the browser executor. */
export type DemoChannel = "api" | "browser";

export type DemoTier = "high" | "medium" | "low";

export interface DemoJobsOptions {
  /** Base URL of the web app (demo ATS pages live under /demo/ats). */
  appUrl: string;
  /** Deterministic "now" (defaults to the current time). */
  now?: Date;
  /** Number of distinct jobs before duplicates are added (default 110, at most the catalogue size). */
  count?: number;
}

